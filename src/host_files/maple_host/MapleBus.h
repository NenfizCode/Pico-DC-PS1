/* Maple Bus host.
 * Ported from DreamPicoPort (OrangeFox86) via OGX-Mini-2026. MIT licensed.
 *
 * Difference from both upstreams: they place maple_out and maple_in in
 * separate PIO blocks, because each is 29 instructions and a block holds 32.
 * PicoGamepadConverter needs the other block for the PS1/PS2 device side, so
 * here a single block holds one program at a time and they are swapped during
 * the write-to-read handoff. See loadProgram() and writeIsr().
 */

#pragma once

#include "MaplePacket.hpp"
#include "maple_config.h"
#include "hardware/pio.h"
#include "hardware/dma.h"
#include <cstdint>

/* Generated by pico_generate_pio_header */
#include "maple_in.pio.h"
#include "maple_out.pio.h"

class MapleBus {
public:
    enum class Phase : uint8_t {
        IDLE = 0,
        WRITE_IN_PROGRESS,
        WRITE_FAILED,
        WRITE_COMPLETE,
        WAITING_FOR_READ_START,
        READ_IN_PROGRESS,
        READ_FAILED,
        READ_COMPLETE,
    };
    enum class FailureReason : uint8_t {
        NONE = 0,
        CRC_INVALID,
        MISSING_DATA,
        BUFFER_OVERFLOW,
        TIMEOUT,
    };
    struct Status {
        Phase phase;
        FailureReason failureReason;
        const uint32_t* readBuffer;
        uint32_t readBufferLen;
        MaplePacket::ByteOrder rxByteOrder;
    };

    /** @param pio  PIO block index (0 or 1) dedicated to the Maple bus.
     *  @param pinA GPIO for data line A; pinA+1 is used for line B.
     *  @param dirPin  Direction-select GPIO, or -1 for the Simple Configuration
     *                 (GPIO tied to the bus through series resistors). */
    MapleBus(uint8_t pio, uint32_t pinA, int32_t dirPin = -1, bool dirOutHigh = true);

    bool write(const MaplePacket& packet, bool autostartRead,
               uint64_t readTimeoutUs = MAPLE_RESPONSE_TIMEOUT_US,
               MaplePacket::ByteOrder rxByteOrder = MaplePacket::ByteOrder::HOST);

    void writeIsr();
    void readIsr();

    Status processEvents(uint64_t currentTimeUs);

    bool isBusy() const { return mCurrentPhase != Phase::IDLE; }

private:
    enum class Loaded : uint8_t { NONE = 0, OUT, IN };

    bool lineCheck();
    void setDirection(bool output);
    /* Overwrites the block's instruction memory. Must stay in RAM: this runs
     * inside the write-complete ISR, where a XIP stall would eat into the
     * handoff budget. */
    void loadProgram(Loaded which);

    pio_hw_t* const mPio;
    const uint32_t mPinA;
    const uint32_t mPinB;
    const int32_t mDirPin;
    const bool mDirOutHigh;
    const uint32_t mMaskA;
    const uint32_t mMaskB;
    const uint32_t mMaskAB;
    const uint mSmOut;
    const uint mSmIn;
    const int mDmaWriteChannel;
    const int mDmaReadChannel;

    /* Built once at construction so the handoff only has to write registers. */
    pio_sm_config mCfgOut;
    pio_sm_config mCfgIn;
    Loaded mLoaded;

    volatile uint32_t mWriteBuffer[258];
    volatile uint32_t mReadBuffer[258];
    uint32_t mLastRead[256];

    Phase mCurrentPhase;
    bool mExpectingResponse;
    uint64_t mResponseTimeoutUs;
    MaplePacket::ByteOrder mRxByteOrder;
    uint64_t mProcKillTime;
    uint64_t mLastReceivedWordTimeUs;
    uint32_t mLastReadTransferCount;
};
